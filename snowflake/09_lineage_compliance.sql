-- 1. DATA LINEAGE TRACKING
-- =====================================================

-- Create comprehensive lineage view
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.DATA_LINEAGE AS
SELECT 
    QUERY_START_TIME,
    QUERY_ID,
    USER_NAME,
    ROLE_NAME,
    WAREHOUSE_NAME,
    DATABASE_NAME,
    SCHEMA_NAME,
    QUERY_TYPE,
    QUERY_TEXT,
    DIRECT_OBJECTS_ACCESSED,
    BASE_OBJECTS_ACCESSED,
    COLUMNS_ACCESSED,
    QUERY_TAG,
    EXECUTION_TIME,
    CREDITS_USED,
    BYTES_SCANNED,
    ROWS_PRODUCED
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY
WHERE QUERY_START_TIME >= DATEADD('day', -30, CURRENT_TIMESTAMP())
    AND (DATABASE_NAME = 'GLOBAL_SPOILAGE_DB' 
         OR QUERY_TEXT ILIKE '%GLOBAL_SPOILAGE%')
ORDER BY QUERY_START_TIME DESC;

-- Create data flow lineage view
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.DATA_FLOW_LINEAGE AS
SELECT 
    QUERY_START_TIME,
    QUERY_ID,
    USER_NAME,
    WAREHOUSE_NAME,
    -- Extract source tables
    REGEXP_SUBSTR_ALL(DIRECT_OBJECTS_ACCESSED, '"objectName":"([^"]+)"', 1, 1, 'e', 1) AS source_tables,
    -- Extract target tables
    REGEXP_SUBSTR_ALL(BASE_OBJECTS_ACCESSED, '"objectName":"([^"]+)"', 1, 1, 'e', 1) AS target_tables,
    QUERY_TEXT,
    EXECUTION_TIME,
    CREDITS_USED
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY
WHERE QUERY_START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
    AND QUERY_TYPE IN ('INSERT', 'UPDATE', 'DELETE', 'MERGE', 'CREATE_TABLE_AS_SELECT')
    AND (DATABASE_NAME = 'GLOBAL_SPOILAGE_DB' 
         OR QUERY_TEXT ILIKE '%GLOBAL_SPOILAGE%')
ORDER BY QUERY_START_TIME DESC;

