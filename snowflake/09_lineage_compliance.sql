-- 4. ACCESS HISTORY MONITORING
-- =====================================================

-- Create access monitoring view
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.ACCESS_MONITORING AS
SELECT 
    DATE(QUERY_START_TIME) AS access_date,
    USER_NAME,
    ROLE_NAME,
    WAREHOUSE_NAME,
    COUNT(*) AS query_count,
    SUM(CREDITS_USED) AS total_credits,
    SUM(BYTES_SCANNED) AS total_bytes_scanned,
    COUNT(DISTINCT QUERY_ID) AS unique_queries,
    MAX(QUERY_START_TIME) AS last_access_time
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY
WHERE QUERY_START_TIME >= DATEADD('day', -30, CURRENT_TIMESTAMP())
    AND (DATABASE_NAME = 'GLOBAL_SPOILAGE_DB' 
         OR QUERY_TEXT ILIKE '%GLOBAL_SPOILAGE%')
GROUP BY DATE(QUERY_START_TIME), USER_NAME, ROLE_NAME, WAREHOUSE_NAME
ORDER BY access_date DESC, total_credits DESC;

-- Create suspicious activity monitoring
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.SUSPICIOUS_ACTIVITY AS
SELECT 
    QUERY_START_TIME,
    USER_NAME,
    ROLE_NAME,
    WAREHOUSE_NAME,
    QUERY_TEXT,
    CREDITS_USED,
    BYTES_SCANNED,
    'HIGH_CREDIT_USAGE' AS activity_type,
    'User consumed ' || CREDITS_USED || ' credits in single query' AS description
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY
WHERE QUERY_START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
    AND CREDITS_USED > 10  -- High credit usage threshold
    AND (DATABASE_NAME = 'GLOBAL_SPOILAGE_DB' 
         OR QUERY_TEXT ILIKE '%GLOBAL_SPOILAGE%')

UNION ALL

SELECT 
    QUERY_START_TIME,
    USER_NAME,
    ROLE_NAME,
    WAREHOUSE_NAME,
    QUERY_TEXT,
    CREDITS_USED,
    BYTES_SCANNED,
    'UNUSUAL_ACCESS_PATTERN' AS activity_type,
    'Access outside normal hours or from unusual location' AS description
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY
WHERE QUERY_START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())
    AND (HOUR(QUERY_START_TIME) < 6 OR HOUR(QUERY_START_TIME) > 22)  -- Outside 6 AM - 10 PM
    AND (DATABASE_NAME = 'GLOBAL_SPOILAGE_DB' 
         OR QUERY_TEXT ILIKE '%GLOBAL_SPOILAGE%')

ORDER BY QUERY_START_TIME DESC;

-- =====================================================
-- 5. COMPLIANCE REPORTING
-- =====================================================

-- Create compliance summary view
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.COMPLIANCE_SUMMARY AS
SELECT 
    CURRENT_DATE() AS report_date,
    'GLOBAL_SPOILAGE' AS project_name,
    (SELECT COUNT(*) FROM GLOBAL_SPOILAGE_DB.OPS.DATA_LINEAGE WHERE QUERY_START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())) AS queries_last_7_days,
    (SELECT COUNT(DISTINCT USER_NAME) FROM GLOBAL_SPOILAGE_DB.OPS.DATA_LINEAGE WHERE QUERY_START_TIME >= DATEADD('day', -7, CURRENT_TIMESTAMP())) AS unique_users_last_7_days,
    (SELECT COUNT(*) FROM GLOBAL_SPOILAGE_DB.OPS.SUSPICIOUS_ACTIVITY) AS suspicious_activities,
    (SELECT COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.TABLES WHERE TABLE_CATALOG = 'GLOBAL_SPOILAGE_DB') AS total_tables,
    (SELECT COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.VIEWS WHERE TABLE_CATALOG = 'GLOBAL_SPOILAGE_DB') AS total_views,
    (SELECT COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.SCHEMATA WHERE CATALOG_NAME = 'GLOBAL_SPOILAGE_DB') AS total_schemas;

-- =====================================================
-- 6. DATA RETENTION COMPLIANCE
-- =====================================================

-- Create retention compliance view
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.RETENTION_COMPLIANCE AS
SELECT 
    TABLE_CATALOG AS database_name,
    TABLE_SCHEMA AS schema_name,
    TABLE_NAME,
    CREATED AS table_created,
    DATEDIFF('day', CREATED, CURRENT_DATE()) AS days_since_creation,
    -- Extract retention days from tags
    GET_TAG('GLOBAL_SPOILAGE_DB.OPS.RETENTION_DAYS', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) AS retention_days,
    CASE 
        WHEN DATEDIFF('day', CREATED, CURRENT_DATE()) > 
             CAST(GET_TAG('GLOBAL_SPOILAGE_DB.OPS.RETENTION_DAYS', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) AS INTEGER) 
        THEN 'OVERDUE_FOR_RETENTION'
        WHEN DATEDIFF('day', CREATED, CURRENT_DATE()) > 
             CAST(GET_TAG('GLOBAL_SPOILAGE_DB.OPS.RETENTION_DAYS', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) AS INTEGER) * 0.8
        THEN 'APPROACHING_RETENTION'
        ELSE 'WITHIN_RETENTION'
    END AS retention_status
FROM SNOWFLAKE.ACCOUNT_USAGE.TABLES
WHERE TABLE_CATALOG = 'GLOBAL_SPOILAGE_DB'
    AND TABLE_TYPE = 'BASE TABLE'
ORDER BY days_since_creation DESC;

-- =====================================================
-- 7. AUDIT EXPORT PROCEDURES
-- =====================================================

-- Procedure to export access history
CREATE OR REPLACE PROCEDURE GLOBAL_SPOILAGE_DB.OPS.SP_EXPORT_ACCESS_HISTORY(
    start_date STRING,
    end_date STRING,
    export_format STRING DEFAULT 'CSV'
)
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    export_result STRING;
    export_path STRING;
BEGIN
    -- Generate export path
    export_path := 'audit_export_' || start_date || '_to_' || end_date || '/';
    
    -- Export access history to stage
    COPY INTO @GLOBAL_SPOILAGE_DB.BACKUP.PRDBACKUP/$(export_path)access_history/
    FROM (
        SELECT *
        FROM GLOBAL_SPOILAGE_DB.OPS.DATA_LINEAGE
        WHERE DATE(QUERY_START_TIME) BETWEEN start_date AND end_date
    )
    FILE_FORMAT = (TYPE = CSV COMPRESSION = GZIP HEADER = TRUE)
    OVERWRITE = TRUE;
    
    SELECT 'ACCESS_HISTORY_EXPORTED_' || export_path INTO export_result;
    
    RETURN export_result;
END;
$$;

-- Procedure to export compliance report
CREATE OR REPLACE PROCEDURE GLOBAL_SPOILAGE_DB.OPS.SP_EXPORT_COMPLIANCE_REPORT()
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    export_result STRING;
    export_path STRING;
BEGIN
    -- Generate export path
    export_path := 'compliance_report_' || TO_VARCHAR(CURRENT_DATE()) || '/';
    
    -- Export compliance summary
    COPY INTO @GLOBAL_SPOILAGE_DB.BACKUP.PRDBACKUP/$(export_path)compliance_summary/
    FROM GLOBAL_SPOILAGE_DB.OPS.COMPLIANCE_SUMMARY
    FILE_FORMAT = (TYPE = CSV COMPRESSION = GZIP HEADER = TRUE)
    OVERWRITE = TRUE;
    
    -- Export retention compliance
    COPY INTO @GLOBAL_SPOILAGE_DB.BACKUP.PRDBACKUP/$(export_path)retention_compliance/
    FROM GLOBAL_SPOILAGE_DB.OPS.RETENTION_COMPLIANCE
    FILE_FORMAT = (TYPE = CSV COMPRESSION = GZIP HEADER = TRUE)
    OVERWRITE = TRUE;
    
    -- Export suspicious activity
    COPY INTO @GLOBAL_SPOILAGE_DB.BACKUP.PRDBACKUP/$(export_path)suspicious_activity/
    FROM GLOBAL_SPOILAGE_DB.OPS.SUSPICIOUS_ACTIVITY
    FILE_FORMAT = (TYPE = CSV COMPRESSION = GZIP HEADER = TRUE)
    OVERWRITE = TRUE;
    
    SELECT 'COMPLIANCE_REPORT_EXPORTED_' || export_path INTO export_result;
    
    RETURN export_result;
END;
$$;

