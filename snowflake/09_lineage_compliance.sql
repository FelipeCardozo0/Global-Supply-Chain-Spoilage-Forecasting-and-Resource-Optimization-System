-- 9. AUTOMATED COMPLIANCE MONITORING
-- =====================================================

-- Task for daily compliance monitoring
CREATE OR REPLACE TASK GLOBAL_SPOILAGE_DB.OPS.TASK_DAILY_COMPLIANCE_CHECK
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = 'USING CRON 0 8 * * * UTC' -- Daily at 8 AM UTC
AS
    -- Check for overdue retention
    INSERT INTO GLOBAL_SPOILAGE_DB.OPS.COMPLIANCE_ALERTS (alert_type, alert_severity, alert_message, affected_object)
    SELECT 
        'RETENTION_OVERDUE',
        'HIGH',
        'Table ' || table_name || ' in ' || schema_name || ' is overdue for retention',
        schema_name || '.' || table_name
    FROM GLOBAL_SPOILAGE_DB.OPS.RETENTION_COMPLIANCE
    WHERE retention_status = 'OVERDUE_FOR_RETENTION';

-- Task for weekly compliance report
CREATE OR REPLACE TASK GLOBAL_SPOILAGE_DB.OPS.TASK_WEEKLY_COMPLIANCE_REPORT
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = 'USING CRON 0 9 * * 1 UTC' -- Weekly on Monday at 9 AM UTC
AS
    CALL GLOBAL_SPOILAGE_DB.OPS.SP_EXPORT_COMPLIANCE_REPORT();

-- =====================================================
-- 10. GDPR COMPLIANCE FEATURES
-- =====================================================

-- Create GDPR compliance view
CREATE OR REPLACE VIEW GLOBAL_SPOILAGE_DB.OPS.GDPR_COMPLIANCE AS
SELECT 
    TABLE_CATALOG AS database_name,
    TABLE_SCHEMA AS schema_name,
    TABLE_NAME,
    GET_TAG('GLOBAL_SPOILAGE_DB.OPS.PII_FLAG', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) AS pii_flag,
    GET_TAG('GLOBAL_SPOILAGE_DB.OPS.GDPR_APPLICABLE', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) AS gdpr_applicable,
    GET_TAG('GLOBAL_SPOILAGE_DB.OPS.DATA_CLASSIFICATION', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) AS data_classification,
    CASE 
        WHEN GET_TAG('GLOBAL_SPOILAGE_DB.OPS.PII_FLAG', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) = 'YES' 
        THEN 'REQUIRES_GDPR_PROTECTION'
        WHEN GET_TAG('GLOBAL_SPOILAGE_DB.OPS.PII_FLAG', TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME) = 'POTENTIAL' 
        THEN 'REVIEW_REQUIRED'
        ELSE 'NO_GDPR_CONCERNS'
    END AS gdpr_status
FROM SNOWFLAKE.ACCOUNT_USAGE.TABLES
WHERE TABLE_CATALOG = 'GLOBAL_SPOILAGE_DB'
    AND TABLE_TYPE = 'BASE TABLE'
ORDER BY gdpr_status DESC, TABLE_NAME;

